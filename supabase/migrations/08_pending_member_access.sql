-- ============================================================================
-- מי שממתין לאישור המנהל צריך לראות שהוא ממתין
--
-- הבעיה שנמצאה בבדיקה: `current_org_id()` מחזירה ארגון רק לחבר פעיל. חבר
-- שהצטרף וממתין לאישור קיבל NULL, ולכן מדיניות הקריאה חסמה אותו מלראות
-- אפילו את השורה של עצמו. התוצאה: הכלי לא זיהה אותו כמשויך לארגון והחזיר
-- אותו למסך החיבור, שם ההצטרפות נכשלה עם "החשבון הזה כבר משויך לארגון".
-- מבוי סתום מוחלט, בלי דרך יציאה.
--
-- התיקון: כל אדם רשאי תמיד לקרוא את השורה שלו ואת שם הארגון שאליו הצטרף,
-- בלי קשר לסטטוס. זה בדיוק המידע שנחוץ כדי להציג "ממתין לאישור" ולא יותר —
-- כל שאר הטבלאות ממשיכות לדרוש חברות פעילה.
-- ============================================================================

drop policy if exists members_read on members;
create policy members_read on members for select to authenticated
  using (
    org_id = current_org_id()      -- חברים פעילים רואים את הארגון שלהם
    or user_id = auth.uid()        -- וכל אחד רואה תמיד את עצמו
  );

drop policy if exists org_read on orgs;
create policy org_read on orgs for select to authenticated
  using (
    id = current_org_id()
    or id in (select org_id from members where user_id = auth.uid())
  );
